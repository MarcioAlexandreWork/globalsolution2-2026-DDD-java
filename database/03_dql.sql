-- ZeladoriaCidadã | Consultas de exemplo (modelo usado também na disciplina de Database Design)

-- 1) INNER JOIN: ocorrências com o cidadão que registrou e a categoria
SELECT o.ID_OCORRENCIA, o.DS_TITULO, c.NM_CIDADAO, ca.NM_CATEGORIA, o.ST_OCORRENCIA
FROM TB_ZC_OCORRENCIA o
INNER JOIN TB_ZC_CIDADAO c ON c.ID_CIDADAO = o.ID_CIDADAO
INNER JOIN TB_ZC_CATEGORIA ca ON ca.ID_CATEGORIA = o.ID_CATEGORIA
ORDER BY o.DT_ABERTURA DESC;

-- 2) INNER JOIN + GROUP BY: quantidade de ocorrências por categoria
SELECT ca.NM_CATEGORIA, COUNT(*) AS QT_OCORRENCIAS
FROM TB_ZC_OCORRENCIA o
INNER JOIN TB_ZC_CATEGORIA ca ON ca.ID_CATEGORIA = o.ID_CATEGORIA
GROUP BY ca.NM_CATEGORIA
ORDER BY QT_OCORRENCIAS DESC;

-- 3) LEFT OUTER JOIN + WHERE + ORDER BY: avenidas e suas ocorrências ainda ABERTAS (inclui avenidas sem nenhuma)
SELECT r.NM_REGIAO, o.ID_OCORRENCIA, o.DS_TITULO
FROM TB_ZC_REGIAO r
LEFT OUTER JOIN TB_ZC_OCORRENCIA o
       ON o.ID_REGIAO = r.ID_REGIAO AND o.ST_OCORRENCIA = 'ABERTA'
WHERE r.NM_REGIAO LIKE 'Avenida%'
ORDER BY r.NM_REGIAO, o.ID_OCORRENCIA;
