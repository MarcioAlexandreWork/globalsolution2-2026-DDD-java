-- ZeladoriaCidadã | DDL (Oracle 12c ou superior: colunas IDENTITY)
-- Ordem de criação respeita as chaves estrangeiras.

CREATE TABLE TB_ZC_CIDADAO (
    ID_CIDADAO   NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_CIDADAO   VARCHAR2(100) NOT NULL,
    DS_EMAIL     VARCHAR2(120) NOT NULL,
    NR_TELEFONE  VARCHAR2(11),
    TP_CIDADAO   VARCHAR2(10)  NOT NULL,
    CONSTRAINT PK_ZC_CIDADAO       PRIMARY KEY (ID_CIDADAO),
    CONSTRAINT UN_ZC_CIDADAO_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_ZC_CIDADAO_TIPO  CHECK (TP_CIDADAO IN ('MORADOR', 'AGENTE'))
);

CREATE TABLE TB_ZC_CATEGORIA (
    ID_CATEGORIA  NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_CATEGORIA  VARCHAR2(60)  NOT NULL,
    DS_CATEGORIA  VARCHAR2(200),
    NR_PRAZO_DIAS NUMBER(3)     NOT NULL,
    CONSTRAINT PK_ZC_CATEGORIA      PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UN_ZC_CATEGORIA_NOME UNIQUE (NM_CATEGORIA),
    CONSTRAINT CK_ZC_CATEGORIA_PRAZO CHECK (NR_PRAZO_DIAS BETWEEN 1 AND 365)
);

CREATE TABLE TB_ZC_REGIAO (
    ID_REGIAO  NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_REGIAO  VARCHAR2(80) NOT NULL,
    NR_CEP     VARCHAR2(9)  NOT NULL,
    CONSTRAINT PK_ZC_REGIAO      PRIMARY KEY (ID_REGIAO),
    CONSTRAINT UN_ZC_REGIAO_NOME UNIQUE (NM_REGIAO)
);

CREATE TABLE TB_ZC_OCORRENCIA (
    ID_OCORRENCIA  NUMBER GENERATED ALWAYS AS IDENTITY,
    DS_TITULO      VARCHAR2(120) NOT NULL,
    DS_OCORRENCIA  VARCHAR2(500),
    ST_OCORRENCIA  VARCHAR2(12)  DEFAULT 'ABERTA' NOT NULL,
    DS_PRIORIDADE  VARCHAR2(5)   DEFAULT 'MEDIA'  NOT NULL,
    DT_ABERTURA    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    DT_RESOLUCAO   TIMESTAMP,
    ID_CIDADAO     NUMBER NOT NULL,
    ID_CATEGORIA   NUMBER NOT NULL,
    ID_REGIAO      NUMBER NOT NULL,
    CONSTRAINT PK_ZC_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT FK_ZC_OCORR_CIDADAO   FOREIGN KEY (ID_CIDADAO)   REFERENCES TB_ZC_CIDADAO (ID_CIDADAO),
    CONSTRAINT FK_ZC_OCORR_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES TB_ZC_CATEGORIA (ID_CATEGORIA),
    CONSTRAINT FK_ZC_OCORR_REGIAO    FOREIGN KEY (ID_REGIAO)    REFERENCES TB_ZC_REGIAO (ID_REGIAO),
    CONSTRAINT CK_ZC_OCORR_STATUS    CHECK (ST_OCORRENCIA IN ('ABERTA', 'EM_ANDAMENTO', 'RESOLVIDA')),
    CONSTRAINT CK_ZC_OCORR_PRIORIDADE CHECK (DS_PRIORIDADE IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT CK_ZC_OCORR_DATAS     CHECK (DT_RESOLUCAO IS NULL OR DT_RESOLUCAO >= DT_ABERTURA)
);

CREATE TABLE TB_ZC_ACOMPANHAMENTO (
    ID_ACOMPANHAMENTO NUMBER GENERATED ALWAYS AS IDENTITY,
    ID_OCORRENCIA     NUMBER        NOT NULL,
    DS_COMENTARIO     VARCHAR2(300) NOT NULL,
    ST_OCORRENCIA     VARCHAR2(12)  NOT NULL,
    DT_REGISTRO       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ZC_ACOMPANHAMENTO PRIMARY KEY (ID_ACOMPANHAMENTO),
    CONSTRAINT FK_ZC_ACOMP_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA)
        REFERENCES TB_ZC_OCORRENCIA (ID_OCORRENCIA) ON DELETE CASCADE,
    CONSTRAINT CK_ZC_ACOMP_STATUS CHECK (ST_OCORRENCIA IN ('ABERTA', 'EM_ANDAMENTO', 'RESOLVIDA'))
);

CREATE INDEX IX_ZC_OCORR_STATUS    ON TB_ZC_OCORRENCIA (ST_OCORRENCIA);
CREATE INDEX IX_ZC_OCORR_CATEGORIA ON TB_ZC_OCORRENCIA (ID_CATEGORIA);
CREATE INDEX IX_ZC_OCORR_REGIAO    ON TB_ZC_OCORRENCIA (ID_REGIAO);
CREATE INDEX IX_ZC_OCORR_CIDADAO   ON TB_ZC_OCORRENCIA (ID_CIDADAO);
CREATE INDEX IX_ZC_ACOMP_OCORR     ON TB_ZC_ACOMPANHAMENTO (ID_OCORRENCIA);
